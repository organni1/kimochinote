import type { DayPlan } from "@/types/plan";
import type { IssueCategory } from "@/types/diagnosis";

const dayOneAction: Record<IssueCategory, string> = {
  contact: "返信の早さではなく、彼が最近してくれた行動を1つ思い出し、感謝を伝える",
  words: "彼が最近してくれた行動を1つ思い出し、言葉にして感謝を伝える",
  abandonment: "不安になった出来事と、実際に彼がしてくれた行動を分けて書き出す",
  future: "大きな将来の話ではなく、近い予定についてやさしく相談する",
  mismatch: "自分が求める愛情表現と、彼がしてくれている行動を分けて整理する",
  general: "彼が最近してくれた行動を1つ思い出し、感謝を伝える",
};

export function buildSevenDayPlan(issueCategory: IssueCategory): DayPlan[] {
  return [
    {
      day: 1,
      title: "感謝を伝える",
      action: dayOneAction[issueCategory],
      example: "この前、予定を合わせてくれて嬉しかった。ありがとう。",
      reason: "感謝の言葉は、彼に「受け入れられている」と感じさせ、安心して行動を続けやすくなります。",
      avoid: "「なんでしてくれないの？」など、不満や疑いをぶつけることは避けましょう。",
      reflection: "今日、彼の行動で受け取れたものは何でしたか？",
    },
    {
      day: 2,
      title: "安心ポイントを整理する",
      action: "自分がどんな時に安心するかを3つ書き出す",
      example: "返信が早い時、次に会う予定が決まっている時、嬉しかったことを言葉にしてくれた時。",
      reason: "安心の条件を知ると、相手に伝える時も責める言い方になりにくくなります。",
      avoid: "不安の原因をすべて彼のせいにしてしまうこと。",
      reflection: "自分にとって一番大きい安心ポイントは何でしたか？",
    },
    {
      day: 3,
      title: "軽く伝える",
      action: "重くならない言葉で、自分の安心ポイントを1つだけ伝える",
      example: "次に会う予定が決まっていると、私はけっこう安心できるみたい。",
      reason: "小さく伝えることで、彼も受け取りやすくなります。",
      avoid: "答えを急がせたり、すぐに反応を求めたりすること。",
      reflection: "伝えたあと、自分の気持ちは少し整理されましたか？",
    },
    { day: 4, title: "受け取る練習", action: "彼の小さな行動を1つ受け取る", example: "連絡をくれたこと、予定を覚えていたことに気づく。", reason: "愛情表現の形を広げて見る練習になります。", avoid: "してくれないことだけを数えること。", reflection: "今日受け取れた小さな行動は何でしたか？" },
    { day: 5, title: "会話を増やす", action: "答えや確認ではなく、共有したい話題を1つ送る", example: "今日これを見て、ちょっとあなたに話したくなった。", reason: "自然な会話の入口が増えると、不安確認以外のつながりを作れます。", avoid: "反応を試すためのメッセージを送ること。", reflection: "会話の入口はやわらかく作れましたか？" },
    { day: 6, title: "未来を小さく話す", action: "近い予定や楽しみについて一緒に話す", example: "来週、少しだけ散歩できたら嬉しいな。", reason: "小さな予定の積み重ねが、関係の見通しにつながります。", avoid: "不安な勢いで大きな結論を迫ること。", reflection: "近い未来について話せたことはありましたか？" },
    { day: 7, title: "一週間を振り返る", action: "安心できた瞬間と、まだ不安な点を分けて書く", example: "安心したことは感謝を伝えられたこと。不安は返信が遅い時に大きくなること。", reason: "事実と不安を分けることで、次に伝えることが見えやすくなります。", avoid: "一週間で関係を完全に判断しようとすること。", reflection: "来週も続けたい小さな行動は何ですか？" },
  ];
}
